# Одинична матриця — це квадратна матриця, у якої на головній діагоналі стоять одиниці, а всі інші елементи дорівнюють нулю. Одиничну матрицю позначають як I. Вона є нейтральним елементом для множення матриць, тобто для будь-якої матриці A виконується рівність A*I = I*A = A.
