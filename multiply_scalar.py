import numpy as np

# Якщо ми будемо до вектора додавати звичайне число, це рівносильно що до кожного елемента нашого вектора ми будемо додавати даний скаляр. Аналогічно і з відніманням. Переконаємось у цьому на прикладі:

a = np.array([1, 2, 3, 4, 5], dtype=float)

print(a)  # [1. 2. 3. 4. 5.]

# а тепер помножимо на 5 наш вектор 
b = 5*a

print(b)  # [ 5. 10. 15. 20. 25.]
